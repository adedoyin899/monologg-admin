import type { FastifyRequest, FastifyReply } from "fastify";
import jwt from "jsonwebtoken";
import { prisma } from "../db/client.js";
import { env } from "../config/env.js";
import { adminAuthVerifier } from "../providers/adminAuth/index.js";
import { hasPermission, type AdminModule } from "../config/adminPermissions.js";
import { audit } from "../services/adminAudit.js";

/**
 * Middleware: requireAdmin
 * Enforces:
 * 1. Bearer token presence and validity via AuthVerifier.
 * 2. Rejection of standard user JWTs from the main app.
 * 3. AdminUser existence and ACTIVE status check.
 * 4. MFA enforcement (aal2) for every route except GET /api/v1/admin/me.
 * 5. AdminSession limits: 8 hours absolute, 30 minutes idle.
 * 6. Audit logging of ADMIN_SIGNIN on new sessions and ACCESS_DENIED on rejections.
 */
export async function requireAdmin(request: FastifyRequest, reply: FastifyReply): Promise<void> {
  const authHeader = request.headers.authorization;
  if (!authHeader || !authHeader.startsWith("Bearer ")) {
    return reply.status(401).send({
      error: "Unauthorized",
      message: "Admin authorization token is missing or invalid.",
    });
  }

  const token = authHeader.split(" ")[1];

  // 1. Explicitly reject user JWTs generated by the main app
  try {
    const userPayload = jwt.verify(token, env.JWT_ACCESS_SECRET) as Record<string, unknown> | null;
    if (userPayload && (userPayload.userId || userPayload.userType)) {
      await audit({
        action: "ACCESS_DENIED",
        reason: "User JWT cannot access admin routes",
        ip: request.ip,
      });
      return reply.status(403).send({
        error: "This account does not have access.",
      });
    }
  } catch {
    // Not a main app user JWT; continue to Admin AuthVerifier
  }

  // 2. Verify admin token via active AuthVerifier
  let verified;
  try {
    verified = await adminAuthVerifier.verify(token);
  } catch (err) {
    const msg = err instanceof Error ? err.message : "Invalid token";
    await audit({
      action: "ACCESS_DENIED",
      reason: `Admin token verification failed: ${msg}`,
      ip: request.ip,
    });
    return reply.status(401).send({
      error: "Unauthorized",
      message: "Invalid or expired admin authentication token.",
    });
  }

  // 3. Find AdminUser by (authProvider, authSubject) or bind allowlisted email
  const email = verified.email.toLowerCase();
  const provider = env.ADMIN_AUTH_PROVIDER === "clerk" ? "CLERK" : "SUPABASE";

  let admin = await prisma.adminUser.findFirst({
    where: {
      authProvider: provider,
      authSubject: verified.subject,
    },
  });

  if (!admin) {
    const pendingAdmin = await prisma.adminUser.findUnique({
      where: { email },
    });

    if (pendingAdmin) {
      admin = await prisma.adminUser.update({
        where: { id: pendingAdmin.id },
        data: {
          authProvider: provider,
          authSubject: verified.subject,
          lastLoginAt: new Date(),
        },
      });
    }
  }

  // If no registered AdminUser exists for this identity:
  if (!admin) {
    await audit({
      action: "ACCESS_DENIED",
      reason: "Non-allowlisted email",
      metadata: { email },
      ip: request.ip,
    });
    return reply.status(403).send({
      error: "This account does not have access.",
    });
  }

  // Check AdminUser status is ACTIVE
  if (admin.status !== "ACTIVE") {
    await audit({
      adminId: admin.id,
      action: "ACCESS_DENIED",
      reason: `Admin account is ${admin.status}`,
      ip: request.ip,
    });
    return reply.status(403).send({
      error: "This account does not have access.",
    });
  }

  // 4. MFA enforcement: every route except GET /api/v1/admin/me requires aal2
  const path = (request.url || "").split("?")[0];
  const isMeRoute = request.method === "GET" && path.endsWith("/admin/me");

  if (!isMeRoute && !verified.mfaVerified) {
    await audit({
      adminId: admin.id,
      action: "ACCESS_DENIED",
      reason: "MFA verification required (aal2)",
      ip: request.ip,
    });
    return reply.status(403).send({
      error: "Multi-factor authentication required.",
      code: "needs_mfa_challenge",
    });
  }

  // 5. Enforce AdminSession limits (8 hours absolute, 30 minutes idle)
  const now = new Date();
  let session = await prisma.adminSession.findFirst({
    where: {
      adminUserId: admin.id,
      providerSessionId: verified.sessionId,
    },
  });

  if (!session) {
    session = await prisma.adminSession.create({
      data: {
        adminUserId: admin.id,
        providerSessionId: verified.sessionId,
        lastSeenAt: now,
      },
    });

    await audit({
      adminId: admin.id,
      action: "ADMIN_SIGNIN",
      targetType: "AdminUser",
      targetId: admin.id,
      ip: request.ip,
      metadata: {
        provider: env.ADMIN_AUTH_PROVIDER,
        mfaVerified: verified.mfaVerified,
      },
    });
  } else {
    const isEnded = session.endedAt !== null;
    const isAbsoluteExpired = now.getTime() - session.createdAt.getTime() > 8 * 60 * 60 * 1000;
    const isIdleExpired = now.getTime() - session.lastSeenAt.getTime() > 30 * 60 * 1000;

    if (isEnded || isAbsoluteExpired || isIdleExpired) {
      if (!isEnded) {
        await prisma.adminSession.update({
          where: { id: session.id },
          data: { endedAt: now },
        }).catch(() => {});
      }
      await audit({
        adminId: admin.id,
        action: "ACCESS_DENIED",
        reason: isEnded
          ? "Session has ended"
          : isAbsoluteExpired
            ? "Session expired: 8-hour absolute limit exceeded"
            : "Session expired: 30-minute idle limit exceeded",
        ip: request.ip,
      });
      return reply.status(401).send({
        error: "Your session has expired. Sign in again.",
      });
    }

    session = await prisma.adminSession.update({
      where: { id: session.id },
      data: { lastSeenAt: now },
    });
  }

  request.adminUser = admin;
  request.adminSession = session;
}

/**
 * Middleware factory: requirePermission
 * Validates that the active adminUser has the required permission level for the given module.
 */
export function requirePermission(module: AdminModule, level: "read" | "write" = "read") {
  return async (request: FastifyRequest, reply: FastifyReply): Promise<void> => {
    const admin = request.adminUser;
    if (!admin) {
      return reply.status(401).send({
        error: "Unauthorized",
        message: "Admin authentication required.",
      });
    }

    const allowed = hasPermission(admin.role, module, level);
    if (!allowed) {
      await audit({
        adminId: admin.id,
        action: "ACCESS_DENIED",
        reason: `Insufficient permissions: requires ${module}:${level} for role ${admin.role}`,
        ip: request.ip,
      });
      return reply.status(403).send({
        error: "Forbidden",
        message: `You do not have permission to access ${module} (${level}).`,
      });
    }
  };
}
